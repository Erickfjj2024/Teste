//! `GuiRedstoneControlTab`, `GuiEnergyTab`, `GuiSecurityTab`, `GuiWarningTab`) and the upgrade window (`GuiUpgradeWindow`).
//!
//! Tabs are positioned outside the main panel (left at x = -26, right at x = gui_width).
//! The upgrade window opens over the screen and handles dragging, row selection, upgrade removal,
//! progress indication, virtual slot positioning, and supported upgrade type inspection.
